//! PDUs from a real RPKI-to-Router session, for the codec and session
//! tests: AGENTS.md §5 asks wire decoders for byte vectors "from real
//! captures" as well as from the RFCs.
//!
//! Source: `wireshark-sample-rpki-rtr_from_rpki.realmv6.org.pcap`, the
//! sample capture attached to Wireshark issue 10411
//! (<https://gitlab.com/wireshark/wireshark/-/issues/10411>), taken on
//! 2013-02-02. A router at 10.23.6.26 talks version 0 (RFC 6810) to the
//! public cache rpki.realmv6.org (141.22.27.142, TCP port 42420). The
//! router sends a Reset Query, then a Serial Query every few seconds. The
//! cache answers the Reset Query with a Cache Response (Session ID
//! 0x6ed8), 2942 IPv4 and 548 IPv6 Prefix PDUs and an End of Data (Serial
//! Number 0x510bd926), and each of the 39 Serial Queries with a Cache
//! Response and the same End of Data. The PDUs were cut by their Length
//! fields from the reassembled TCP streams; every one is canonical.
//!
//! Only a selection of the Prefix PDUs is kept, in the order of the reply:
//! both families, Max Length equal to and longer than the Prefix Length,
//! and 2- and 4-octet ASNs.

